"""Writes ntc_tables.h next to this file: the thermistors' ADC counts against temperature, from the
B-equation, for the firmware's lookup (the chip has no maths library). Run: python3 ntc_tables.py"""
import math
import os


def table(r_top, r25, beta, t_from, t_to, step):
    rows = []
    for t in range(t_from, t_to + 1, step):
        r = r25 * math.exp(beta * (1 / (t + 273.15) - 1 / 298.15))
        rows.append((round(4095 * r / (r + r_top)), t * 10))
    return rows


def emit(name, rows, comment):
    out = f"/* {comment} */\nstatic const ntc_point {name}[] = {{\n"
    line = "   "
    for raw, c10 in rows:
        item = f" {{{raw}, {c10}}},"
        if len(line) + len(item) > 100:
            out += line + "\n"
            line = "   "
        line += item
    return out + line + "\n};\n"


text = ("/* Generated by ntc_tables.py from the B-equation: ADC counts (12 bit, ratiometric) against\n"
        " * 0.1 C, the counts falling as the temperature rises. */\n")
text += emit("HX_NTC", table(470, 50000, 3950, -40, 350, 10),
             "Heat exchanger: 50 kOhm at 25 C, B 3950 K, under 470 Ohm (OVH-9, ASSUMED until measured)")
text += emit("BOARD_NTC", table(10000, 10000, 3434, -40, 130, 5),
             "Board: NCP18XH103 (10 kOhm at 25 C, B 3434 K) under 10 kOhm (TS-2)")
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "ntc_tables.h"), "w") as f:
    f.write(text)
