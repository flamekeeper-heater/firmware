"""The board's web page: a browser app's build folder (web_app) turned into a C++
table of gzipped files at compile time (flamekeeper/web_files.h). Plain Python, no ESPHome.
"""

from __future__ import annotations

import gzip
import hashlib
import re
from pathlib import Path

# What the board serves, by extension. Anything else in the build is refused, so nothing is served
# with a type the browser has to guess.
TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".mjs": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json",
    ".webmanifest": "application/manifest+json",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".webp": "image/webp",
    ".woff2": "font/woff2",
    ".txt": "text/plain; charset=utf-8",
}
# Skipped: the source maps (the board has no use for them, and they are large).
SKIP = {".map"}
# Vite's content hash: "index-CkksxKgm.js". Such a file never changes under its name.
HASHED = re.compile(r"-[A-Za-z0-9_-]{8}\.[a-z0-9]+$")
# The page's security policy forbids inline scripts (flamekeeper_net.cpp, CSP).
INLINE_SCRIPT = re.compile(r"<script\b(?![^>]*\bsrc=)[^>]*>\s*\S", re.IGNORECASE)


class WebPageError(Exception):
    pass


def collect(dist: Path) -> list[dict]:
    """The files to serve: path, type, gzipped bytes, ETag, whether immutable."""
    if not (dist / "index.html").is_file():
        raise WebPageError(f"{dist} has no index.html")
    files = []
    for f in sorted(p for p in dist.rglob("*") if p.is_file()):
        rel = f.relative_to(dist).as_posix()
        if f.suffix in SKIP or f.name.startswith("."):
            continue
        ctype = TYPES.get(f.suffix.lower())
        if ctype is None:
            raise WebPageError(f"{rel}: no content type for '{f.suffix}' (web_page.py, TYPES)")
        if not re.fullmatch(r"[A-Za-z0-9._/-]+", rel):
            raise WebPageError(f"{rel}: only letters, digits, '.', '_', '-' and '/' in file names")
        raw = f.read_bytes()
        if f.suffix == ".html" and INLINE_SCRIPT.search(raw.decode("utf-8", "replace")):
            raise WebPageError(f"{rel}: an inline <script>; the page's security policy blocks it")
        gz = gzip.compress(raw, compresslevel=9, mtime=0)
        files.append(
            {
                "path": "/" + rel,
                "type": ctype,
                "gz": gz,
                "raw_size": len(raw),
                "etag": '"' + hashlib.sha256(gz).hexdigest()[:16] + '"',
                "immutable": bool(HASHED.search(f.name)) and f.suffix != ".html",
            }
        )
    return files


def header(files: list[dict], source: str) -> str:
    """The C++ table flamekeeper_net.cpp includes."""
    out = [
        "// Generated by flamekeeper_net/web_page.py at compile time. Do not edit.",
        f"// Source: {source}",
        "#pragma once",
        '#include "esphome/components/flamekeeper/web_files.h"',
        "",
        "namespace esphome {",
        "namespace flamekeeper_net {",
        "",
    ]
    for i, f in enumerate(files):
        out.append(f"// {f['path']}: {f['raw_size']} bytes, {len(f['gz'])} gzipped")
        out.append(f"static const uint8_t WEB_GZ_{i}[] = {{")
        gz = f["gz"]
        for k in range(0, len(gz), 24):
            out.append("  " + ",".join(f"0x{b:02x}" for b in gz[k : k + 24]) + ",")
        out.append("};")
    out.append("static const ::esphome::flamekeeper::web::File WEB_FILES[] = {")
    for i, f in enumerate(files):
        etag = f["etag"].replace('"', '\\"')
        immutable = "true" if f["immutable"] else "false"
        out.append(
            f'  {{"{f["path"]}", "{f["type"]}", "{etag}", WEB_GZ_{i}, sizeof(WEB_GZ_{i}), {immutable}}},'
        )
    if not files:
        out.append('  {"", "", "", nullptr, 0, false},  // no web app built in')
    out.append("};")
    out.append(f"static const size_t WEB_FILE_COUNT = {len(files)};")
    out += ["", "}  // namespace flamekeeper_net", "}  // namespace esphome", ""]
    return "\n".join(out)
